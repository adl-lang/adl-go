package main

import (
	"fmt"
	"os"
	"text/template"
)

func main() {
	cmd := &texprV2Cmd{}
	cmd.Run()
}

type texprV2Cmd struct {
}

var (
	tmpl = `
func Texpr_{{.ADL}}() ATypeExpr[{{.Go}}] {
	te := Make_TypeExpr(
		Make_TypeRef_primitive("{{.ADL}}"),
		[]TypeExpr{},
	)
	return Make_ATypeExpr[{{.Go}}](te)
}
`
	paramTmpl = `
func Texpr_{{.ADL}}[T any](te ATypeExpr[T]) ATypeExpr[{{.Go}}T] {
	te0 := Make_TypeExpr(
		Make_TypeRef_primitive("{{.ADL}}"),
		[]TypeExpr{
			te.Value,
		},
	)
	return Make_ATypeExpr[{{.Go}}T](te0)
}
`
)

var texprData = []struct {
	ADL   string
	Go    string
	param bool
}{
	{"Vector", "[]", true},
	{"StringMap", "map[string]", true},
	{"Nullable", "*", true},
	{"Int8", "int8", false},
	{"Int16", "int16", false},
	{"Int32", "int32", false},
	{"Int64", "int64", false},
	{"Word8", "uint8", false},
	{"Word16", "uint16", false},
	{"Word32", "uint32", false},
	{"Word64", "uint64", false},
	{"Bool", "bool", false},
	{"Float", "float64", false},
	{"Double", "float64", false},
	{"String", "string", false},
	// {"ByteVector", "[]byte"},
	{"Void", "struct{}", false},
	{"Json", "any", false},
}

func (in *texprV2Cmd) Run() error {
	t, err := template.New("").Parse(tmpl)
	if err != nil {
		return err
	}
	pt, err := template.New("").Parse(paramTmpl)
	if err != nil {
		return err
	}
	fmt.Printf(`// Code generated by gen_prim_texpr - DO NOT EDIT.
package adlast
`)
	for _, te := range texprData {
		if te.param {
			err = pt.Execute(os.Stdout, te)
		} else {
			err = t.Execute(os.Stdout, te)
		}
		if err != nil {
			return err
		}
	}
	return nil
}
